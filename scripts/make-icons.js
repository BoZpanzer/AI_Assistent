// Renders the JARVIS mark with Chromium and writes build/icon.png, build/tray.png, build/icon.ico
const { app, BrowserWindow, nativeImage } = require('electron');
const fs = require('node:fs');
const path = require('node:path');

const svg = (size, tray) => `<!doctype html><html style="overflow:hidden"><body style="margin:0;background:transparent;overflow:hidden">
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 256 256">
  <defs>
    <radialGradient id="bg" cx="50%" cy="45%" r="60%"><stop offset="0%" stop-color="#0b2a44"/><stop offset="100%" stop-color="#030a14"/></radialGradient>
    <radialGradient id="core" cx="50%" cy="50%" r="50%"><stop offset="0%" stop-color="#ffffff"/><stop offset="35%" stop-color="#7ff0ff"/><stop offset="100%" stop-color="#22d3ee" stop-opacity="0"/></radialGradient>
    <filter id="g" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="${tray ? 2 : 5}" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>
  </defs>
  ${tray ? '' : '<rect x="8" y="8" width="240" height="240" rx="56" fill="url(#bg)" stroke="#22d3ee" stroke-opacity="0.55" stroke-width="4"/>'}
  <g filter="url(#g)" fill="none" stroke="#38e1ff" stroke-width="${tray ? 16 : 9}" stroke-linejoin="round">
    <path d="M128 ${tray ? 14 : 38} L${tray ? 242 : 218} 128 L128 ${tray ? 242 : 218} L${tray ? 14 : 38} 128 Z"/>
  </g>
  <path d="M128 78 L139 117 L178 128 L139 139 L128 178 L117 139 L78 128 L117 117 Z" fill="#bff7ff" filter="url(#g)"/>
  <circle cx="128" cy="128" r="30" fill="url(#core)"/>
</svg></body></html>`;

async function render(size, tray) {
  const w = new BrowserWindow({ width: size, height: size, show: false, transparent: true, backgroundColor: '#00000000', frame: false, webPreferences: { offscreen: true } });
  const tmp = path.join(require('node:os').tmpdir(), `jarvis-icon-${size}-${tray ? 't' : 'a'}.html`);
  fs.writeFileSync(tmp, svg(size, tray));
  await w.loadFile(tmp);
  await new Promise((r) => setTimeout(r, 300));
  const img = await w.webContents.capturePage({ x: 0, y: 0, width: size, height: size });
  w.destroy();
  return img;
}

function ico(pngs) {
  // ICO container with embedded PNG images (supported since Windows Vista).
  const header = Buffer.alloc(6); header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(pngs.length, 4);
  const dir = Buffer.alloc(16 * pngs.length);
  let offset = 6 + dir.length;
  pngs.forEach(({ size, data }, i) => {
    const o = i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, o); dir.writeUInt8(size >= 256 ? 0 : size, o + 1);
    dir.writeUInt8(0, o + 2); dir.writeUInt8(0, o + 3); dir.writeUInt16LE(1, o + 4); dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(data.length, o + 8); dir.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, dir, ...pngs.map((p) => p.data)]);
}

app.on('window-all-closed', () => {});
app.whenReady().then(async () => {
  const out = path.join(__dirname, '..', 'build');
  fs.mkdirSync(out, { recursive: true });
  const big = await render(256, false);
  fs.writeFileSync(path.join(out, 'icon.png'), big.toPNG());
  const tray = await render(64, true);
  fs.writeFileSync(path.join(out, 'tray.png'), tray.resize({ width: 32, height: 32, quality: 'best' }).toPNG());
  const sizes = [16, 24, 32, 48, 64, 128, 256];
  const pngs = sizes.map((s) => ({ size: s, data: s === 256 ? big.toPNG() : big.resize({ width: s, height: s, quality: 'best' }).toPNG() }));
  fs.writeFileSync(path.join(out, 'icon.ico'), ico(pngs));
  // NSIS installer header/sidebar images are generated by build-win.mjs
  console.log('Icons geschrieben:', fs.readdirSync(out).join(', '));
  app.quit();
});
